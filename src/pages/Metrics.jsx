import { useEffect, useState } from "react";
import { api } from "../api.js";
import Icon from "../components/Icon.jsx";

// Evaluation results, read live from ml/artifacts/metrics.json via the API.
export default function Metrics() {
  const [m, setM] = useState(null);
  const [h, setH] = useState(null);
  const [err, setErr] = useState(null);
  useEffect(() => {
    api.metrics().then(setM).catch((e) => setErr(e.message));
    api.health().then(setH).catch(() => {});
  }, []);
  if (err) return <div className="banner bad"><Icon name="alert" />{err}</div>;
  if (!m) return <div className="empty">Loading results…</div>;
  const ev = m.metrics;
  if (!ev || !ev.set_a) return <div className="banner warn"><Icon name="info" />No evaluation results yet. Run <code>python ml/train_all.py</code>.</div>;

  const A = ev.set_a, B = ev.set_b;
  const fa = (set) => set.conversations["rules+ml"].false_alarms;
  const sms = ev.sms_spam_real, urlA = ev.urls.eval_unseen_domains, urlB = ev.urls.eval_cross_source;

  return (
    <>
      <h1>How well it works</h1>
      <p className="muted">All numbers are measured on held-out data the models never trained on, and are regenerated by <code>python ml/train_all.py</code>.</p>

      <div className="tiles">
        {ev.external ? <Tile value={ev.external.message_model.f1.toFixed(2)} label={`F1 on ${ev.external.n.toLocaleString()} real messages (Kaggle ScamShield), before: ${ev.external.before ? ev.external.before.message_model.f1.toFixed(2) : "-"}`} /> : null}
        {ev.external ? <Tile value={`${Math.round(ev.external.message_model.recall_real_scam_types * 100)}%`} label="Real scam types caught (UPI, KYC, courier, lottery…)" /> : null}
        <Tile value={A.conversations["rules+ml"].scams_stopped} label="Scam calls stopped (test set A)" />
        <Tile value={B.conversations["rules+ml"].scams_stopped} label="Family-emergency & marketplace scams stopped (test set B)" />
        <Tile value={`${frac(fa(A))[0] + frac(fa(B))[0]}/${frac(fa(A))[1] + frac(fa(B))[1]}`} label="False alarms on genuine calls (A + B)" />
        <Tile value={sms.f1.toFixed(2)} label={`F1 on ${sms.n.toLocaleString()} real SMS (spam/scam model)`} />
        <Tile value={urlA.f1.toFixed(2)} label={`F1 on ${urlA.n.toLocaleString()} URLs from unseen domains`} />
        <Tile value={`${ev.latency.rules_plus_ml_ms_per_utterance} ms`} label="Per utterance, CPU only, offline" />
      </div>

      {ev.external ? (
        <Section title={`Real messages: ${ev.external.n.toLocaleString()} from the Kaggle ScamShield test split (never trained on)`}>
          <table>
            <thead><tr><th>Model</th><th className="num">Precision</th><th className="num">Recall</th><th className="num">F1</th><th className="num">False positives</th><th className="num">Real scam types caught</th></tr></thead>
            <tbody>
              {ev.external.before ? <ExtRow name="Message model, before real data" r={ev.external.before.message_model} /> : null}
              <ExtRow name="Message model, now" r={ev.external.message_model} strong />
              {ev.external.before?.checker_scam_verdict ? <ExtRow name="Full checker, before" r={ev.external.before.checker_scam_verdict} /> : null}
              {ev.external.checker_scam_verdict ? <ExtRow name="Full checker, now" r={ev.external.checker_scam_verdict} strong /> : null}
            </tbody>
          </table>
          <p className="tiny" style={{ marginTop: 8 }}>
            Data: ScamShield: Multilingual Smishing Social Engn (siddharthrane07, Kaggle, MIT License). Cleaned before use: its copy of our UCI data,
            machine-translated Hindi, duplicates and anything matching our own test sets removed. Marketing spam counts as "scam" in this dataset,
            so real scam types are shown separately.
          </p>
        </Section>
      ) : null}

      <Section title="Whole conversations: rules alone vs. rules + trained model">
        <table>
          <thead><tr><th>Test set</th><th>System</th><th className="num">Scams stopped</th><th className="num">False alarms</th><th className="num">Alert before last turn</th></tr></thead>
          <tbody>
            {[["A (original)", A], ["B (new scam types)", B]].flatMap(([name, set]) => ["rules", "rules+ml"].map((sys) => {
              const r = set.conversations[sys];
              return <tr key={name + sys}><td>{name}</td><td>{sys === "rules" ? "Rules only" : "Rules + trained model"}</td><td className="num">{r.scams_stopped}</td><td className="num">{r.false_alarms}</td><td className="num">{r.alert_before_final_turn}</td></tr>;
            }))}
          </tbody>
        </table>
        {B.before ? <p className="tiny" style={{ marginTop: 8 }}>Set B before adding family-emergency and marketplace coverage: {B.before.conversations["rules+ml"].scams_stopped} stopped. Set B was frozen (SHA-256) before any new training data was written.</p> : null}
      </Section>

      <Section title="Tactic detection per utterance">
        <table>
          <thead><tr><th>Test set</th><th>System</th><th className="num">Precision</th><th className="num">Recall</th><th className="num">F1</th></tr></thead>
          <tbody>
            {[["A", A], ["B", B]].flatMap(([name, set]) => ["rules", "ml", "rules+ml"].map((sys) => {
              const r = set.utterances[sys];
              return <tr key={name + sys}><td>{name}</td><td>{{ rules: "Rules only", ml: "Trained model only", "rules+ml": "Combined" }[sys]}</td><td className="num">{r.precision}</td><td className="num">{r.recall}</td><td className="num">{r.f1}</td></tr>;
            }))}
          </tbody>
        </table>
      </Section>

      <Section title="Message checker and phishing links">
        <table>
          <thead><tr><th>Test</th><th className="num">n</th><th className="num">Precision</th><th className="num">Recall</th><th className="num">F1</th><th className="num">False positives</th></tr></thead>
          <tbody>
            <tr><td>Checker, set A messages ("scam" verdict)</td><td className="num">{A.messages.n}</td><Cells r={A.messages.checker_scam_verdict} /></tr>
            <tr><td>Checker, set B messages ("scam" verdict)</td><td className="num">{B.messages.n}</td><Cells r={B.messages.checker_scam_verdict} /></tr>
            <tr><td>Real UCI SMS Spam test split</td><td className="num">{sms.n}</td><td className="num">{sms.precision}</td><td className="num">{sms.recall}</td><td className="num">{sms.f1}</td><td className="num">{sms.false_positive_rate}</td></tr>
            <tr><td>URLs, unseen domains</td><td className="num">{urlA.n.toLocaleString()}</td><td className="num">{urlA.precision}</td><td className="num">{urlA.recall}</td><td className="num">{urlA.f1}</td><td className="num">{urlA.false_positive_rate}</td></tr>
            <tr><td>URLs, cross-source (harder)</td><td className="num">{urlB.n.toLocaleString()}</td><td className="num">{urlB.precision}</td><td className="num">{urlB.recall}</td><td className="num">{urlB.f1}</td><td className="num">{urlB.false_positive_rate}</td></tr>
          </tbody>
        </table>
      </Section>

      <Section title="Live system">
        <table>
          <tbody>
            <tr><td>Rules</td><td>{h ? "on" : "…"}</td></tr>
            <tr><td>Trained models</td><td>{h ? (h.layers.tactic_model && h.layers.message_model ? "loaded" : "missing") : "…"}</td></tr>
            <tr><td>LLM second opinion</td><td>{h ? (h.layers.llm.enabled ? `on (${h.layers.llm.model})` : "off (no API key): the product runs fully without it") : "…"}</td></tr>
            <tr><td>Utterances scored this run</td><td>{m.live.utterances_scored}{m.live.share_without_llm != null ? ` · ${Math.round(m.live.share_without_llm * 100)}% needed no LLM call` : ""}</td></tr>
          </tbody>
        </table>
      </Section>

      <Section title="Honesty notes">
        <ul style={{ margin: 0, paddingLeft: 18 }}>
          <li>Conversation training data is synthetic (template-generated). Message training data is mostly real (UCI SMS Spam, Kaggle ScamShield); URL data is real.</li>
          <li>No test item is a near-copy of a training item (automatic check, max similarity {ev.contamination.max_similarity}).</li>
          <li>Both test sets were written by the same author as the training templates; set B was frozen first. Test sets are small: quote the fractions.</li>
          <li>The intel graph includes synthetic demo campaigns, labelled as such everywhere.</li>
        </ul>
      </Section>
    </>
  );
}

function frac(s) {
  const [a, b] = String(s).split("/").map(Number);
  return [a || 0, b || 0];
}
function Tile({ value, label }) {
  return <div className="tile"><div className="value">{value}</div><div className="label">{label}</div></div>;
}
function ExtRow({ name, r, strong }) {
  const v = (x) => (strong ? <strong>{x}</strong> : x);
  return (
    <tr><td>{v(name)}</td><td className="num">{r.precision}</td><td className="num">{r.recall}</td><td className="num">{v(r.f1)}</td>
      <td className="num">{r.false_positive_rate}</td><td className="num">{v(`${Math.round((r.recall_real_scam_types ?? 0) * 100)}%`)}</td></tr>
  );
}
function Section({ title, children }) {
  return <div className="card"><h2>{title}</h2><div className="table-wrap">{children}</div></div>;
}
function Cells({ r }) {
  return <><td className="num">{r.precision}</td><td className="num">{r.recall}</td><td className="num">{r.f1}</td><td className="num">{r.false_positive_rate}</td></>;
}
